names = list(positions.keys())
filtered_pairs = []
SPATIAL_THRESHOLD = 500

for i in range(len(names)):
    for j in range(i+1, len(names)):
        p1 = positions[names[i]]["pos"]
        p2 = positions[names[j]]["pos"]
        dist = math.sqrt(sum((p2[k] - p1[k])**2 for k in range(3)))
        if dist < SPATIAL_THRESHOLD:
            filtered_pairs.append((names[i], names[j]))

print(f"\n[STAGE 1] Filtered pairs (within {SPATIAL_THRESHOLD} km): {len(filtered_pairs)}")

close_approaches = []
for pair in filtered_pairs:
    n1, n2 = pair
    p1, v1 = positions[n1]["pos"], positions[n1]["vel"]
    p2, v2 = positions[n2]["pos"], positions[n2]["vel"]
    r = [p2[k] - p1[k] for k in range(3)]
    v = [v2[k] - v1[k] for k in range(3)]
    v_sq = sum(x**2 for x in v)
    if v_sq == 0:
        continue
    r_dot_v = sum(r[k] * v[k] for k in range(3))
    tca = -r_dot_v / v_sq
    if tca < 0:
        continue
    future_r = [r[k] + v[k] * tca for k in range(3)]
    dca = math.sqrt(sum(x**2 for x in future_r))
    if dca < 50:
        close_approaches.append((n1, n2, tca, dca))

print(f"[STAGE 2] Close approaches (DCA < 50 km): {len(close_approaches)}")

if close_approaches:
    close_approaches.sort(key=lambda x: x[3])
    for ca in close_approaches:
        print(f"  {ca[0]} <-> {ca[1]}: TCA={ca[2]:.2f}s, DCA={ca[3]:.2f} km")
else:
    print("  No close approaches found.")
