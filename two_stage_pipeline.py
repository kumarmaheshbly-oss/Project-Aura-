def parse_tle(tle_text):
    lines = [l.strip() for l in tle_text.strip().split("\n") if l.strip()]
    satellites = []
    i = 0
    while i < len(lines):
        if lines[i].startswith("0 "):
            name = lines[i][2:].strip()
            if i+2 < len(lines):
                satellites.append({"name": name, "line1": lines[i+1], "line2": lines[i+2]})
                i += 3
            else:
                break
        else:
            i += 1
    return satellites

